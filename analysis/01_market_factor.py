"""
Phase 1: market-factor regression for XAR.

Question: how much of XAR's movement is just the overall stock market,
and how much is left over for defense-specific drivers?

What it does
  1. Downloads weekly prices for XAR, SPY (S&P 500), ^VIX and ^TNX (10-yr yield).
  2. Regresses XAR's weekly return on SPY's return  (CAPM: alpha + beta).
  3. Adds VIX and 10-yr yield changes to see if they explain more.
  4. Saves the data and a plain-English summary, and writes the results
     into the website (data/results.js) so the Drivers/Findings tabs can use them.

Run it from the repo folder:
    pip install -r requirements.txt
    python analysis/01_market_factor.py
"""
import json
import sys
from datetime import date
from pathlib import Path

import pandas as pd
import statsmodels.api as sm

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "analysis" / "output"
START = "2015-01-01"
TICKERS = {"XAR": "XAR", "SPY": "SPY", "VIX": "^VIX", "TNX": "^TNX"}


def download_prices(start=START):
    import yfinance as yf
    raw = yf.download(list(TICKERS.values()), start=start, interval="1wk",
                      auto_adjust=True, progress=False)
    close = raw["Close"].rename(columns={v: k for k, v in TICKERS.items()})
    return close[list(TICKERS)].dropna()


def build_features(prices):
    df = pd.DataFrame(index=prices.index)
    df["xar_ret"] = prices["XAR"].pct_change() * 100      # % weekly return
    df["spy_ret"] = prices["SPY"].pct_change() * 100
    df["vix_chg"] = prices["VIX"].diff()                  # VIX points
    df["tnx_chg"] = prices["TNX"].diff()                  # yield change, % points
    return df.dropna()


def fit(df, cols):
    X = sm.add_constant(df[cols])
    return sm.OLS(df["xar_ret"], X).fit(cov_type="HC1")   # robust std. errors


def summarize(m1, m2, df):
    beta = m1.params["spy_ret"]
    alpha_wk = m1.params["const"]
    lines = [
        f"# XAR market-factor regression ({df.index[0].date()} to {df.index[-1].date()}, {len(df)} weeks)",
        "",
        "## Model 1: XAR return = alpha + beta x S&P 500 return",
        f"- Beta: {beta:.2f}  (XAR moves about {beta:.2f}% for every 1% the S&P 500 moves)",
        f"- Alpha: {alpha_wk:.3f}% per week (p = {m1.pvalues['const']:.3f})",
        f"- R-squared: {m1.rsquared:.2f}  -> the market explains about {m1.rsquared*100:.0f}% of XAR's weekly moves;",
        f"  about {(1-m1.rsquared)*100:.0f}% is left for defense-specific drivers to explain.",
        "",
        "## Model 2: + VIX change + 10-yr yield change",
    ]
    for k in ["spy_ret", "vix_chg", "tnx_chg"]:
        lines.append(f"- {k}: coef {m2.params[k]:.3f}, p = {m2.pvalues[k]:.3f}"
                     + ("  (significant)" if m2.pvalues[k] < 0.05 else ""))
    lines += [f"- R-squared: {m2.rsquared:.2f} (vs {m1.rsquared:.2f} with the market alone)", "",
              "## Full output", "```", str(m2.summary()), "```"]
    return "\n".join(lines)


def write_site_results(m1, m2, df):
    def sig(m, k):
        return "Significant" if m.pvalues[k] < 0.05 else "Not significant"
    results = {
        "updated": str(date.today()),
        "period": f"{df.index[0].date()} to {df.index[-1].date()}",
        "weeks": len(df),
        "beta": round(m1.params["spy_ret"], 3),
        "alphaWeekly": round(m1.params["const"], 4),
        "r2Market": round(m1.rsquared, 3),
        "r2WithMacro": round(m2.rsquared, 3),
        "drivers": {
            "S&P 500 returns": {"status": sig(m2, "spy_ret"), "result": f"beta {m2.params['spy_ret']:.2f}, p={m2.pvalues['spy_ret']:.3f}"},
            "Volatility": {"status": sig(m2, "vix_chg"), "result": f"coef {m2.params['vix_chg']:.3f}, p={m2.pvalues['vix_chg']:.3f}"},
            "10-year Treasury yield": {"status": sig(m2, "tnx_chg"), "result": f"coef {m2.params['tnx_chg']:.3f}, p={m2.pvalues['tnx_chg']:.3f}"},
        },
    }
    (ROOT / "data" / "results.js").write_text(
        "// Generated by analysis/01_market_factor.py. Do not edit by hand.\n"
        "window.RESULTS = " + json.dumps(results, indent=2) + ";\n", encoding="utf-8")


def main(prices=None):
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    if prices is None:
        print("Downloading weekly prices for XAR, SPY, VIX, 10-yr yield...")
        prices = download_prices()
    prices.to_csv(OUT_DIR / "prices_weekly.csv")
    df = build_features(prices)
    m1 = fit(df, ["spy_ret"])
    m2 = fit(df, ["spy_ret", "vix_chg", "tnx_chg"])
    text = summarize(m1, m2, df)
    (OUT_DIR / "market_factor.md").write_text(text, encoding="utf-8")
    write_site_results(m1, m2, df)
    print(text.split("## Full output")[0])
    print(f"Saved: {OUT_DIR / 'market_factor.md'}, {OUT_DIR / 'prices_weekly.csv'}, data/results.js")


if __name__ == "__main__":
    sys.exit(main())
